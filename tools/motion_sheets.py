    md = ["# 고양이 동작 설명서", "", "프로그램에서 고양이가 하는 모든 동작입니다. 그림은 각 동작의 연속 장면 6컷(왼쪽→오른쪽)이고, 설명은 언제 나오는지와 몸이 어떻게 움직이는지입니다.", ""]
    n = 0
    for ci, (cat, items) in enumerate(CATEGORIES, 1):
        W = TEXT_W + 6 * CW + PAD * 2
        H = 70 + len(items) * (CH + 8) + 10
        sheet = Image.new("RGB", (W, H), "#f7f5f0")
        d = ImageDraw.Draw(sheet)
        d.text((PAD, 16), f"{cat}  ({len(items)}가지)", font=FONT_H, fill="#222")
        note = "  (쉬는 동안은 호흡으로 몸이 아주 조금씩만 움직여서 컷 사이 차이가 작습니다)" if cat in ("쉬기", "잠자기") else ""
        d.text((PAD, 52), "왼쪽 → 오른쪽 순서로 이어지는 6컷" + note, font=FONT_S, fill="#777")
        md += [f"## {ci}. {cat}", ""]
        for ri, (name, code, specs, desc, sc) in enumerate(items):
            n += 1
            y = 74 + ri * (CH + 8)
            d.rectangle((PAD, y, W - PAD, y + CH), outline="#d8d4c8", fill="#fffdf8")
            d.text((PAD + 10, y + 8), f"{n}. {name}", font=FONT_B, fill="#222")
            ty = y + 40
            for line in desc:
                for w in wrap(d, clean(line), FONT, TEXT_W - 24):
                    d.text((PAD + 10, ty), w, font=FONT, fill="#444")
                    ty += 22
                ty += 4
            for k, spec in enumerate(specs):
                sheet.paste(frame_image(code, spec, 0.98 * sc, CW - 4, CH - 4), (PAD + TEXT_W + k * CW + 2, y + 2))
            md += [f"### {n}. {name}", ""] + [f"- {x}" for x in desc] + [""]
        path = out / f"{ci}_{cat.replace(' · ', '·')}.png"
        sheet.save(path)
        print("저장:", path.name, sheet.size)
    (out / "동작_설명서.md").write_text("\n".join(md), encoding="utf-8")
    print(f"동작 {n}가지, 설명서:", out / "동작_설명서.md")


