def frame_image(code, spec, scale, cw, ch):
    clock, t, u, extra = spec
    an = Animator(code)
    an.clock, an.t, an.u = clock, t, u
    an.param = dict(extra)
    img = QImage(cw, ch, QImage.Format.Format_ARGB32)
    img.fill(QColor("#dff0ec"))
    p = QPainter(img)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    p.setPen(QColor(0, 0, 0, 50))
    gy = ch - (118 if code == "hold" else 34)          # 집어 올린 자세는 꼬리가 아래로 길게 늘어져서 위로 올려 그린다
    p.drawLine(0, gy, cw, gy)
    RIG.tail.a = None
    RIG.detail = 1.0
    RIG.draw(p, an.pose(), clock + 7.0, 1, scale, origin=(cw * 0.56, gy))
    p.end()
    ptr = img.constBits()
    ptr.setsize(img.sizeInBytes())
    return Image.frombuffer("RGBA", (cw, ch), bytes(ptr), "raw", "BGRA", 0, 1).convert("RGB")


import re

_EMOJI = re.compile("[𐀀-􏿿☀-➿️]")


def clean(text):
    """그림용 글꼴(맑은 고딕)에는 이모지가 없어서 빈 네모가 되므로 그림에 쓸 글에서는 뺀다 (설명서 문서에는 그대로 둔다)."""
    return re.sub(r" +", " ", _EMOJI.sub("", text)).replace(' "', ' "').replace("( ", "(").replace(' ")', '")')


def wrap(draw, text, font, width):
    lines, cur = [], ""
    for chunk in text:
        if draw.textlength(cur + chunk, font=font) > width:
            lines.append(cur)
            cur = chunk.lstrip()
        else:
            cur += chunk
    if cur:
        lines.append(cur)
    return lines


